/** Плачей с причинами или «что помогло»: шаг засчитывается, когда подробности сохранили. */
private func countDetailed(_ events: [any BabyEvent]) -> Int {
    events.count { event in
        guard let crying = event as? Crying else { return false }
        return !crying.reasons.isEmpty || !crying.helped.isEmpty
    }
}
